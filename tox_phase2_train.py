"""
=============================================================
Real-Time Toxic Content Moderation
Phase 2: Model Training & Evaluation (TensorFlow / Keras)
=============================================================
Author : Setu Patel
Requires: processed/*.csv and preprocessing_config.json
          (generated by tox_phase1_explore_preprocess.py)
Output : models/tox_model.keras      full model: raw text in, 6 scores out
         models/thresholds.json      tuned per-label decision thresholds
         models/phase2_metrics.json  every number printed below

RUN THE SMOKE TEST FIRST:
    python .\\tox_phase2_train.py --smoke
It trains a tiny model on ~3,000 comments for one epoch and runs every
step of the real pipeline (build, train, predict, tune, save, reload).
It should finish in a minute or two. If anything about the TensorFlow
setup is wrong, you find out now instead of 20 minutes into the real run.
Then the real thing:
    python .\\tox_phase2_train.py
Optional: --epochs N (default 3), --max-len N (shorter = faster).
The model is saved right after training, BEFORE evaluation. If anything goes
wrong later, `python .\\tox_phase2_train.py --eval-only` reloads it and redoes
just the evaluation -- no retraining.

Design notes
------------
* One shared network, six sigmoid outputs (multi-label). Phase 1 showed
  the labels overlap heavily (95% of severe_toxic comments are also
  obscene), so a shared representation is a better fit than six models.
* Two inputs: the comment text AND its uppercase ratio. Phase 1 found
  mostly-CAPS comments are flagged ~6.5x as often as normal-case ones, but
  Keras' text layer lowercases everything -- so the shouting signal is
  fed in separately.
* Class imbalance (only ~10% of comments are flagged; `threat` is 0.3%)
  is handled at the DECISION stage, not by reweighting the loss: the model
  trains with plain binary cross-entropy, then each label's threshold is
  tuned on the validation set. Accuracy is deliberately never reported --
  a model that flags nothing would score ~90%.
* Two operating points per label are saved:
    f1             -- the threshold that maximizes F1 on validation data
    high_precision -- the most permissive threshold that reaches 90%
                      validation precision and is at least as strict as
                      the F1 one (None if the label can't get there)
  The model will be pointed at r/AskReddit, where toxic comments are
  probably far rarer than in this Wikipedia training data, so the stricter
  mode is the safer default for a live display.
* The TEST split is used once, at the end, for reporting only. All tuning
  uses the validation split.
=============================================================
"""

import os

os.environ.setdefault("TF_CPP_MIN_LOG_LEVEL", "2")  # hide TF's INFO/WARNING chatter
os.environ["KERAS_BACKEND"] = "tensorflow"           # must be set before importing keras

import argparse
import json
import math
import time

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, precision_recall_curve, roc_auc_score

import keras
import tensorflow as tf
from keras import layers

from tox_common import LABEL_COLS
from tox_scoring import (
    CAPS_KEY, MODEL_FILE, TEXT_KEY, THRESHOLDS_FILE,
    make_dataset, make_inputs, predict_probs, score_texts, threshold_vector,
)

# ── Config ─────────────────────────────────────────────────
PROCESSED_DIR = "processed"
SEED = 42
EMBED_DIM = 64
LSTM_UNITS = 64
DENSE_UNITS = 64
LEARNING_RATE = 1e-3
BATCH_SIZE = 128
DEFAULT_EPOCHS = 3
PRECISION_TARGET = 0.90
MIN_FLAGGED_FOR_PRECISION_TARGET = 10  # ignore thresholds that flag fewer than this
pd.set_option("display.width", 130)

# Neutral spot-check sentences scored at the end (nothing offensive on purpose).
SPOT_CHECKS = [
    "Thanks so much, this was really helpful!",
    "What is the best way to learn Python?",
    "WHAT IS WRONG WITH YOU PEOPLE",
    "I will find you and you will regret this",
]


def parse_args():
    p = argparse.ArgumentParser(description="Train the toxicity classifier.")
    p.add_argument("--smoke", action="store_true",
                   help="tiny fast run to verify the whole pipeline end to end")
    p.add_argument("--epochs", type=int, default=DEFAULT_EPOCHS)
    p.add_argument("--max-len", type=int, default=None,
                   help="override the sequence length from preprocessing_config.json")
    p.add_argument("--eval-only", action="store_true",
                   help="skip training: load the saved model and redo only the "
                        "evaluation and reports (no retraining after a reporting bug)")
    return p.parse_args()


def get_settings(args):
    with open(os.path.join(PROCESSED_DIR, "preprocessing_config.json")) as f:
        cfg = json.load(f)
    s = {
        "max_len": args.max_len or cfg["recommended_max_len"],
        "vocab_size": cfg["recommended_vocab_size"],
        "epochs": args.epochs,
        "batch_size": BATCH_SIZE,
        "n_train": None, "n_val": None, "n_test": None,
        "out_dir": "models",
        "smoke": bool(args.smoke),
    }
    if args.smoke:
        s.update(max_len=60, vocab_size=3000, epochs=1, batch_size=64,
                 n_train=3000, n_val=800, n_test=800, out_dir="models_smoke")
    return s


# ── Data ───────────────────────────────────────────────────
def load_split(name, n_rows):
    df = pd.read_csv(os.path.join(PROCESSED_DIR, f"{name}.csv"))
    df["text"] = df["text"].fillna("").astype(str)
    if n_rows is not None and n_rows < len(df):
        df = df.sample(n=n_rows, random_state=SEED).reset_index(drop=True)
    inputs = make_inputs(df["text"].tolist())
    labels = df[LABEL_COLS].to_numpy(dtype=np.float32)
    return inputs, labels


# ── Model (the TensorFlow-specific part) ───────────────────
def build_model(vocab_size, max_len, train_texts):
    """Builds the two-input classifier. `train_texts` is a 1-D array of
    training strings used to learn the vocabulary (adapt)."""
    # WINDOWS ENCODING FIX. A TextVectorization layer that learned its vocabulary
    # via adapt() saves that vocabulary to a separate text file using the OS
    # default encoding (cp1252 on Windows), which crashes on characters like the
    # invisible left-to-right mark (\u200e) common in Wikipedia text. A layer
    # built with an explicit `vocabulary=` instead stores it inside the model's
    # JSON config, where non-ASCII characters are escaped -- no encoding issue.
    # So: learn the vocabulary with a throwaway layer, then build the real one
    # from that list.
    adapter = layers.TextVectorization(
        max_tokens=vocab_size, output_mode="int", output_sequence_length=max_len)
    adapter.adapt(tf.data.Dataset.from_tensor_slices(train_texts).batch(1024))
    vectorizer = layers.TextVectorization(
        output_mode="int",
        output_sequence_length=max_len,
        vocabulary=adapter.get_vocabulary(),
        name="vectorizer",
    )

    text_in = keras.Input(shape=(1,), dtype="string", name=TEXT_KEY)
    caps_in = keras.Input(shape=(1,), dtype="float32", name=CAPS_KEY)

    x = vectorizer(text_in)
    x = layers.Embedding(input_dim=vectorizer.vocabulary_size(),
                         output_dim=EMBED_DIM, name="embedding")(x)
    x = layers.SpatialDropout1D(0.2)(x)
    x = layers.Bidirectional(layers.LSTM(LSTM_UNITS, return_sequences=True),
                             name="bilstm")(x)
    x = layers.GlobalMaxPooling1D(name="max_pool")(x)

    c = layers.Dense(8, activation="relu", name="caps_dense")(caps_in)
    x = layers.Concatenate(name="merge")([x, c])
    x = layers.Dense(DENSE_UNITS, activation="relu", name="hidden")(x)
    x = layers.Dropout(0.3)(x)
    out = layers.Dense(len(LABEL_COLS), activation="sigmoid", name="labels")(x)

    model = keras.Model(inputs={TEXT_KEY: text_in, CAPS_KEY: caps_in},
                        outputs=out, name="tox_classifier")
    model.compile(
        optimizer=keras.optimizers.Adam(learning_rate=LEARNING_RATE),
        loss="binary_crossentropy",
        metrics=[
            # num_labels makes Keras build the metric's state up front rather
            # than lazily mid-training, which avoids a class of tracing errors.
            keras.metrics.AUC(name="roc_auc", multi_label=True, num_labels=len(LABEL_COLS)),
            keras.metrics.AUC(name="pr_auc", curve="PR", multi_label=True, num_labels=len(LABEL_COLS)),
        ],
    )
    return model


def train(model, train_inputs, train_labels, val_inputs, val_labels, epochs, batch_size):
    train_ds = make_dataset(train_inputs, train_labels, batch_size, shuffle=True, seed=SEED)
    val_ds = make_dataset(val_inputs, val_labels, batch_size)
    callbacks = [keras.callbacks.EarlyStopping(
        monitor="val_loss", patience=1, restore_best_weights=True)]
    return model.fit(train_ds, validation_data=val_ds, epochs=epochs,
                     callbacks=callbacks, verbose=1)


def save_and_verify(model, out_dir, val_inputs, n_check=256):
    """Saves the model, reloads it from disk, and checks the reloaded copy
    gives the same scores. Phase 3 depends on the saved file working, so
    this is verified now rather than discovered later."""
    path = os.path.join(out_dir, MODEL_FILE)
    model.save(path)
    loaded = keras.models.load_model(path)
    sub = {k: v[:n_check] for k, v in val_inputs.items()}
    diff = float(np.max(np.abs(predict_probs(model, sub) - predict_probs(loaded, sub))))
    return path, diff, loaded


# ── Metrics & threshold tuning (pure numpy/sklearn) ────────
def confusion_metrics(truth, pred):
    truth = np.asarray(truth, dtype=bool)
    pred = np.asarray(pred, dtype=bool)
    tp = int((truth & pred).sum())
    fp = int((~truth & pred).sum())
    fn = int((truth & ~pred).sum())
    precision = tp / (tp + fp) if (tp + fp) > 0 else float("nan")
    recall = tp / (tp + fn) if (tp + fn) > 0 else float("nan")
    if tp > 0:
        f1 = 2 * precision * recall / (precision + recall)
    else:
        f1 = 0.0 if (fp + fn) > 0 else float("nan")
    return {"tp": tp, "fp": fp, "fn": fn, "flagged": tp + fp,
            "precision": precision, "recall": recall, "f1": f1}


def ranking_metrics(y_true, probs):
    """ROC-AUC and PR-AUC per label, with positive counts. A label with no
    positives (or no negatives) in the sample can't be scored -> NaN."""
    rows = []
    for j, label in enumerate(LABEL_COLS):
        y, p = y_true[:, j], probs[:, j]
        n_pos = int(y.sum())
        if n_pos == 0 or n_pos == len(y):
            roc = pr = float("nan")
        else:
            roc = float(roc_auc_score(y, p))
            pr = float(average_precision_score(y, p))
        rows.append({"label": label, "positives": n_pos, "roc_auc": roc, "pr_auc": pr})
    return rows


def tune_thresholds(y_val, p_val):
    """Per-label thresholds chosen on VALIDATION data only."""
    f1_thr, hp_thr = {}, {}
    for j, label in enumerate(LABEL_COLS):
        y, p = y_val[:, j], p_val[:, j]
        if y.sum() == 0:  # nothing to tune on
            f1_thr[label], hp_thr[label] = 0.5, None
            continue
        prec, rec, thr = precision_recall_curve(y, p)
        prec, rec = prec[:-1], rec[:-1]          # align with `thr`
        f1 = 2 * prec * rec / np.maximum(prec + rec, 1e-12)
        f1_thr[label] = float(thr[int(np.argmax(f1))])

        # High-precision mode = the most permissive threshold that (a) reaches
        # the precision target, (b) flags enough comments to be meaningful, and
        # (c) is at least as strict as the F1-optimal threshold. Without (c),
        # a label whose F1 point already beats the target would get a "strict"
        # threshold LOOSER than its normal one.
        n_flagged = len(p) - np.searchsorted(np.sort(p), thr, side="left")
        ok = np.where((prec >= PRECISION_TARGET)
                      & (n_flagged >= MIN_FLAGGED_FOR_PRECISION_TARGET)
                      & (thr >= f1_thr[label]))[0]
        hp_thr[label] = float(thr[ok[0]]) if len(ok) else None
    return f1_thr, hp_thr


def operating_point_rows(y_true, probs, thresholds_by_label):
    rows = []
    for j, label in enumerate(LABEL_COLS):
        t = thresholds_by_label[label]
        if t is None:
            rows.append({"label": label, "threshold": None, "tp": 0, "fp": 0, "fn": int(y_true[:, j].sum()),
                         "flagged": 0, "precision": float("nan"), "recall": 0.0, "f1": float("nan")})
            continue
        m = confusion_metrics(y_true[:, j] > 0, probs[:, j] >= t)
        rows.append({"label": label, "threshold": float(t), **m})
    return rows


def any_label_metrics(y_true, probs, thr_vec):
    """The dashboard's real decision rule: flag a comment if ANY label's
    score reaches its threshold, judged against 'any label is truly on'."""
    return confusion_metrics(y_true.max(axis=1) > 0, (probs >= thr_vec).any(axis=1))


def nan_to_none(obj):
    """json.dump writes NaN as a bare NaN token, which isn't valid JSON."""
    if isinstance(obj, dict):
        return {k: nan_to_none(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [nan_to_none(v) for v in obj]
    if isinstance(obj, (float, np.floating)) and (math.isnan(obj) or math.isinf(obj)):
        return None
    if isinstance(obj, np.generic):
        return obj.item()
    return obj


# ── Reporting ──────────────────────────────────────────────
def show(df, float_cols, title):
    print(f"\n{'─' * 60}\n  {title}\n{'─' * 60}")
    out = df.copy()
    for c in float_cols:
        out[c] = out[c].map(lambda v: "n/a" if v is None or (isinstance(v, float) and math.isnan(v)) else f"{v:.3f}")
    print(out.to_string(index=False))


def report(rank_rows, f1_rows, hp_rows, any_f1, any_hp):
    show(pd.DataFrame(rank_rows), ["roc_auc", "pr_auc"],
         "TEST — ranking quality per label (positives = how many real cases)")
    show(pd.DataFrame(f1_rows)[["label", "threshold", "flagged", "precision", "recall", "f1"]],
         ["threshold", "precision", "recall", "f1"],
         "TEST — F1-optimal operating point (thresholds tuned on validation)")
    show(pd.DataFrame(hp_rows)[["label", "threshold", "flagged", "precision", "recall"]],
         ["threshold", "precision", "recall"],
         f"TEST — high-precision operating point (validation precision >= {PRECISION_TARGET:.0%})")
    print(f"\n{'─' * 60}\n  TEST — the dashboard's rule: flag if ANY label crosses its threshold\n{'─' * 60}")
    for name, m in [("F1-optimal thresholds", any_f1), ("High-precision thresholds", any_hp)]:
        print(f"  {name:<26} flagged {m['flagged']:>5}  precision {m['precision']:.3f}  "
              f"recall {m['recall']:.3f}  f1 {m['f1']:.3f}")


def spot_check(model, thr_f1):
    print(f"\n{'─' * 60}\n  Spot check — neutral sentences scored end to end from raw text\n{'─' * 60}")
    probs = score_texts(model, SPOT_CHECKS)
    for text, p in zip(SPOT_CHECKS, probs):
        j = int(np.argmax(p))
        shown = text if len(text) <= 42 else text[:39] + "..."
        print(f"  {shown:<42} top label: {LABEL_COLS[j]:<13} score {p[j]:.3f}")


# ── Main ───────────────────────────────────────────────────
def load_prior_metrics(out_dir):
    path = os.path.join(out_dir, "phase2_metrics.json")
    if os.path.exists(path):
        with open(path) as f:
            return json.load(f)
    return {}


def main():
    args = parse_args()
    s = get_settings(args)
    os.makedirs(s["out_dir"], exist_ok=True)
    keras.utils.set_random_seed(SEED)
    t_start = time.time()
    model_path = os.path.join(s["out_dir"], MODEL_FILE)

    tag = "  [SMOKE TEST]" if s["smoke"] else ("  [EVAL ONLY]" if args.eval_only else "")
    print("=" * 60)
    print("  Toxic Moderation — Phase 2: Training" + tag)
    print("=" * 60)
    print(f"  max_len={s['max_len']}  vocab={s['vocab_size']:,}  epochs={s['epochs']}  "
          f"batch={s['batch_size']}  output -> {s['out_dir']}/")

    print("\n[1/6] Loading data ...")
    tr_in, tr_y = load_split("train", s["n_train"])
    va_in, va_y = load_split("val", s["n_val"])
    te_in, te_y = load_split("test", s["n_test"])
    print(f"  train {len(tr_y):,}  val {len(va_y):,}  test {len(te_y):,} comments")

    diff = None
    if args.eval_only:
        print("\n[2/6] Loading the saved model (--eval-only: no training) ...")
        if not os.path.exists(model_path):
            raise SystemExit(f"No saved model at {model_path}. Run without --eval-only first.")
        model = keras.models.load_model(model_path)
        scoring_model = model
        prior = load_prior_metrics(s["out_dir"])
        history_dict = prior.get("history", {})
        epochs_run = prior.get("epochs_run")
        prior_diff = prior.get("reload_max_abs_diff")
        print("\n[3/6] Training skipped.")
        print("\n[4/6] Model save skipped (already saved).")
        diff = prior_diff
    else:
        print("\n[2/6] Building model (learning the vocabulary) ...")
        model = build_model(s["vocab_size"], s["max_len"], tr_in[TEXT_KEY][:, 0])
        model.summary()

        print("\n[3/6] Training ...")
        t_fit = time.time()
        history = train(model, tr_in, tr_y, va_in, va_y, s["epochs"], s["batch_size"])
        print(f"  training took {(time.time() - t_fit) / 60:.1f} min")
        history_dict = {k: [float(v) for v in vals] for k, vals in history.history.items()}
        epochs_run = len(history.history.get("loss", []))

        # Saved BEFORE evaluating, so a problem in the evaluation code can never
        # cost a training run.
        print("\n[4/6] Saving the model and verifying it reloads correctly ...")
        path, diff, scoring_model = save_and_verify(model, s["out_dir"], va_in)
        status = "OK" if diff < 1e-4 else "WARNING: reloaded model disagrees -- do NOT use it yet"
        print(f"  saved {path}")
        print(f"  max score difference after reload: {diff:.2e}  [{status}]")

    print("\n[5/6] Scoring, tuning thresholds on validation, reporting on test ...")
    p_val = predict_probs(model, va_in)
    p_test = predict_probs(model, te_in)
    f1_thr, hp_thr = tune_thresholds(va_y, p_val)
    rank_rows = ranking_metrics(te_y, p_test)
    f1_rows = operating_point_rows(te_y, p_test, f1_thr)
    hp_rows = operating_point_rows(te_y, p_test, hp_thr)
    thresholds = {
        "label_cols": LABEL_COLS,
        "model_file": MODEL_FILE,
        "f1_threshold": f1_thr,
        "high_precision_threshold": hp_thr,
        "precision_target": PRECISION_TARGET,
        "tuned_on": "validation split",
        "max_len": s["max_len"],
        "vocab_size": s["vocab_size"],
    }
    thr_f1_vec = threshold_vector(thresholds, "f1")
    thr_hp_vec = threshold_vector(thresholds, "high_precision")
    any_f1 = any_label_metrics(te_y, p_test, thr_f1_vec)
    any_hp = any_label_metrics(te_y, p_test, thr_hp_vec)
    report(rank_rows, f1_rows, hp_rows, any_f1, any_hp)
    spot_check(scoring_model, f1_thr)

    print("\n[6/6] Writing reports ...")
    with open(os.path.join(s["out_dir"], THRESHOLDS_FILE), "w") as f:
        json.dump(nan_to_none(thresholds), f, indent=2)
    metrics = {
        "settings": s,
        "epochs_run": epochs_run,
        "history": history_dict,
        "test_ranking": rank_rows,
        "test_f1_operating_point": f1_rows,
        "test_high_precision_operating_point": hp_rows,
        "test_any_label_f1_thresholds": any_f1,
        "test_any_label_high_precision_thresholds": any_hp,
        "reload_max_abs_diff": diff,
    }
    with open(os.path.join(s["out_dir"], "phase2_metrics.json"), "w") as f:
        json.dump(nan_to_none(metrics), f, indent=2)
    print(f"  [saved] {os.path.join(s['out_dir'], THRESHOLDS_FILE)}")
    print(f"  [saved] {os.path.join(s['out_dir'], 'phase2_metrics.json')}")
    print(f"\n  Total time: {(time.time() - t_start) / 60:.1f} min")

    if s["smoke"]:
        print("\n  Smoke test finished. The scores above are meaningless (tiny model, tiny data) --")
        print("  what matters is that every step ran. Now run the real thing:")
        print("      python .\\tox_phase2_train.py")


if __name__ == "__main__":
    main()
